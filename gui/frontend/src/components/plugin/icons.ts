/** A plugin's icon by name: the allowlisted lucide icon, else a circle (undefined name: `fallback`). */
export function pluginIcon(name: string | undefined, fallback: LucideIcon = Puzzle): LucideIcon {
  if (!name) return fallback;
  return PLUGIN_ICONS[name] ?? Circle;
}
