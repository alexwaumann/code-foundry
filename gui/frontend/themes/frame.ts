/**
 * The frame stylesheet's committed parts (docs/notes/theme-css-route.md). The daemon serves
 * GET /cf/theme.css to pages the model writes: a `:root` block of the published theme's
 * slots, then internal/theme/frame.css (this file's frameCss: the component aliases, the
 * radius scale and the type roles as plain CSS). Before the GUI publishes, it serves the
 * GitHub defaults from internal/theme/frame-defaults.json (frameDefaultsJson). Both are
 * written by `pnpm run themes` with the catalogs; themes/frame.test.ts fails on drift.
 * The daemon derives nothing: every colour here is a var() of a slot the GUI resolved.
 */
import { DEFAULT_DARK, DEFAULT_LIGHT } from "../src/themes/defaults.ts";
import { COMPONENT_ALIASES, resolveSlots, type ThemeFile } from "../src/themes/slots.ts";
import { remRole } from "../src/pagelib/theme.ts";

/** Roles a page has no use for: the sidebar's app name. */
const SKIPPED_ROLES = new Set(["text-brand"]);

/** The radius steps a page may use (index.css's scale), plus --radius the pane step reads. */
const RADII = ["--radius-sm", "--radius-md", "--radius-lg", "--radius-xl", "--radius-2xl", "--radius-pane"];

/** What index.css's roles and body read that Tailwind (absent in a page) would declare. */
const PAGE_VARS: readonly [string, string][] = [
  ["--tracking-tight", "-0.025em"],
  ["--font-sans", `-apple-system, BlinkMacSystemFont, "SF Pro Text", "Helvetica Neue", sans-serif`],
  ["--font-mono", `ui-monospace, "SF Mono", Menlo, monospace`],
];

export interface Role {
  name: string;
  decls: [string, string][];
  /** Nested blocks (`&:hover { … }`), selector suffix and declarations. */
  nested: { suffix: string; decls: [string, string][] }[];
}

/** The body of the `{` at open (its index), and the index after its matching `}`. */
function block(css: string, open: number): { body: string; end: number } {
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}" && --depth === 0) return { body: css.slice(open + 1, i), end: i + 1 };
  }
  throw new Error("index.css: unbalanced braces");
}

function declarations(body: string): [string, string][] {
  const out: [string, string][] = [];
  for (const part of body.split(";")) {
    const d = part.replace(/\/\*[\s\S]*?\*\//g, "").trim();
    const colon = d.indexOf(":");
    if (!d || colon < 0) continue;
    out.push([d.slice(0, colon).trim(), d.slice(colon + 1).trim()]);
  }
  return out;
}

/** A colour that reads a component name reads its slot instead, so a page needs only the slots. */
function slotValue(prop: string, value: string): string {
  if (prop !== "color") return value;
  return value.replace(/var\((--[a-z0-9-]+)\)/g, (m, name: string) => {
    const slot = COMPONENT_ALIASES[name];
    return slot ? `var(${slot})` : m;
  });
}

/** index.css's type roles (`@utility text-* { … }`), in order, without the sidebar-only ones. */
export function typeRoles(indexCss: string): Role[] {
  const roles: Role[] = [];
  const re = /@utility (text-[a-z0-9-]+)\s*\{/g;
  for (let m = re.exec(indexCss); m; m = re.exec(indexCss)) {
    const name = m[1] ?? "";
    const { body, end } = block(indexCss, m.index + m[0].length - 1);
    re.lastIndex = end;
    if (SKIPPED_ROLES.has(name)) continue;
    const nested: Role["nested"] = [];
    let flat = "";
    let i = 0;
    for (const n of body.matchAll(/&([^{;]*)\{/g)) {
      const at = n.index;
      if (at < i) continue;
      flat += body.slice(i, at);
      const inner = block(body, at + n[0].length - 1);
      nested.push({ suffix: (n[1] ?? "").trim(), decls: declarations(inner.body).map(([p, v]) => [p, slotValue(p, v)]) });
      i = inner.end;
    }
    flat += body.slice(i);
    roles.push({ name, decls: declarations(flat).map(([p, v]) => [p, slotValue(p, v)]), nested });
  }
  if (roles.length === 0) throw new Error("index.css: no type roles found");
  return roles;
}

/** index.css's radius scale and --radius, in RADII order then --radius. */
export function radii(indexCss: string): [string, string][] {
  const find = (name: string): string => {
    const m = new RegExp(`${name}:\\s*([^;]+);`).exec(indexCss);
    if (!m?.[1]) throw new Error(`index.css: no ${name}`);
    return m[1].trim();
  };
  return [...RADII.map((n): [string, string] => [n, find(n)]), ["--radius", find("--radius")]];
}

const decl = ([p, v]: [string, string]) => `  ${p}: ${v};`;

/** internal/theme/frame.css: everything in /cf/theme.css except the published slots. */
export function frameCss(indexCss: string): string {
  const root = [...Object.entries(COMPONENT_ALIASES).map(([name, slot]): [string, string] => [name, `var(${slot})`]), ...radii(indexCss), ...PAGE_VARS];
  const out = [
    "/* Code Foundry's frame stylesheet, after the published slots (docs/notes/theme-css-route.md).",
    " * Generated by gui/frontend/themes/convert.ts (`pnpm run themes`) from src/themes/slots.ts",
    " * and src/index.css; never edit by hand. Component names alias the slots as index.css does,",
    " * then the radius scale, then the type roles. :where() keeps the page defaults at zero",
    " * specificity, so any rule of the page's own wins. The roles sit in Tailwind's utilities",
    " * layer, as index.css's @utility roles do in the app, so a colour or weight utility of",
    " * /cf/ui.css or /cf/tailwind.js (later in that layer) beats them; the statement names",
    " * Tailwind's layer order first, so a layer this file opens keeps its place. */",
    "@layer theme, base, components, utilities;",
    ":root {",
    ...root.map(decl),
    "}",
    ":where(html) {",
    "  background-color: var(--cf-surface);",
    "  color: var(--cf-text);",
    "  font-family: var(--font-sans);",
    "}",
    ":where(code, kbd, pre, samp) {",
    "  font-family: var(--font-mono);",
    "}",
    ":where(a) {",
    "  color: var(--cf-link);",
    "}",
    "::selection {",
    "  background-color: var(--cf-selection);",
    "}",
  ];
  out.push("@layer utilities {");
  // In rem, as /cf/ui.css's roles (remRole): a page scales its type from the root.
  const inner = ([p, v]: [string, string]) => "  " + decl([p, remRole(`${p}: ${v}`).slice(p.length + 2)]);
  for (const r of typeRoles(indexCss)) {
    out.push(`  .${r.name} {`, ...r.decls.map(inner), "  }");
    for (const n of r.nested) out.push(`  .${r.name}${n.suffix} {`, ...n.decls.map(inner), "  }");
  }
  out.push("}");
  return out.join("\n") + "\n";
}

/** internal/theme/frame-defaults.json: the default theme of each scheme, resolved. */
export function frameDefaultsJson(catalog: ThemeFile[]): string {
  const entry = (id: string) => {
    const t = catalog.find((c) => c.id === id);
    if (!t) throw new Error(`default theme ${id} is not in the catalog`);
    return { id: t.id, scheme: t.scheme, vars: resolveSlots(t) };
  };
  return JSON.stringify({ dark: entry(DEFAULT_DARK), light: entry(DEFAULT_LIGHT) }, null, 2) + "\n";
}
