// The frame stylesheet (docs/notes/theme-css-route.md): pages the model writes (the File
// tab's HTML preview today) link GET /cf/theme.css and paint in the user's theme. The GUI
// resolves the slots (gui/frontend/src/themes/slots.ts) and publishes them
// (UiService.PublishTheme); the daemon only keeps the last one and writes it out. Nothing
// is derived here: frame.css (the component aliases, radius scale and type roles, every
// colour a var() of a slot) and frame-defaults.json (GitHub Dark and Light, resolved,
// served until the GUI publishes) are generated by gui/frontend/themes/convert.ts
// (`bun run themes`) and committed; gui/frontend/themes/frame.test.ts fails on drift.

// FramePrefix is the route the frame handler is mounted on. It serves a closed list of
// paths (FrameCSSPath, FrameJSONPath) and nothing that takes a path parameter.
const FramePrefix = "/cf/"

// The frame routes.
const (
	FrameCSSPath  = FramePrefix + "theme.css"
	FrameJSONPath = FramePrefix + "theme.json"
)

// maxVars bounds a published theme before its names are compared with SlotNames.
const maxVars = 512

//go:embed frame.css
var frameCSS string

//go:embed frame-defaults.json
var frameDefaultsJSON []byte

// Frame is one theme as pages see it: the id, the scheme and every resolved slot.
type Frame struct {
	ID     string            `json:"id"`
	Scheme string            `json:"scheme"`
	Vars   map[string]string `json:"vars"`
}

var frameDefaults = parseFrameDefaults(frameDefaultsJSON)

// slotNames is every slot the GUI resolves, sorted: the names a published theme must carry,
// no more and no fewer. Read from the defaults, which are resolved by the same rules
// (gui/frontend/src/themes/slots.ts) and regenerated with them, so the set never drifts
// from the GUI's; GUI and daemon always ship together.
var slotNames = slices.Sorted(maps.Keys(frameDefaults[SchemeDark].Vars))

// SlotNames returns every slot name a published theme carries, sorted.
func SlotNames() []string { return slices.Clone(slotNames) }

// parseFrameDefaults reads the embedded defaults. A malformed file is a build defect
// TestFrameDefaults catches, so it yields empty frames rather than a panic.
func parseFrameDefaults(data []byte) map[string]Frame {
	var d map[string]Frame
	if err := json.Unmarshal(data, &d); err != nil {
		return map[string]Frame{}
	}
	return d
}

// DefaultFrame is the scheme's default theme (GitHub Dark or Light), resolved by the GUI's
// rules when the catalog was generated.
func DefaultFrame(scheme string) Frame { return frameDefaults[scheme].clone() }

func (f Frame) clone() Frame {
	f.Vars = maps.Clone(f.Vars)
	return f
}

var (
	frameIDRe   = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{0,63}$`)
	frameNameRe = regexp.MustCompile(`^--(cf|terminal|syn|sh)-[a-z0-9-]{1,64}$`)
	frameHexRe  = regexp.MustCompile(`^#[0-9a-fA-F]{6}([0-9a-fA-F]{2})?$`)
)

// Check reports why f cannot be published: an id that is not lowercase letters, digits
// and dashes, a scheme other than dark or light, no vars or too many, a name outside the
// slot families or a value that is not #rrggbb / #rrggbbaa, or a set of names other than
// exactly SlotNames (a missing slot would leave a var() undefined in every page; an
// unknown one is a misspelling). The names and values go into a stylesheet verbatim, so
// nothing else is let through.
func (f Frame) Check() error {
	switch {
	case !frameIDRe.MatchString(f.ID):
		return fmt.Errorf("theme id %q: want lowercase letters, digits and dashes", f.ID)
	case f.Scheme != SchemeDark && f.Scheme != SchemeLight:
		return fmt.Errorf("unknown scheme %q", f.Scheme)
	case len(f.Vars) == 0:
		return errors.New("no vars")
	case len(f.Vars) > maxVars:
		return fmt.Errorf("%d vars; at most %d", len(f.Vars), maxVars)
	}
	for _, name := range slices.Sorted(maps.Keys(f.Vars)) {
		if !frameNameRe.MatchString(name) {
			return fmt.Errorf("var %q: want --cf-*, --terminal-*, --syn-* or --sh-*", name)
		}
		if v := f.Vars[name]; !frameHexRe.MatchString(v) {
			return fmt.Errorf("var %s: %q is not #rrggbb or #rrggbbaa", name, v)
		}
	}
	return checkSlotSet(f.Vars)
}

// checkSlotSet reports the names vars lacks and the ones it has that are not slots.
func checkSlotSet(vars map[string]string) error {
	var missing, unknown []string
	for _, name := range slotNames {
		if _, ok := vars[name]; !ok {
			missing = append(missing, name)
		}
	}
	for _, name := range slices.Sorted(maps.Keys(vars)) {
		if _, ok := slices.BinarySearch(slotNames, name); !ok {
			unknown = append(unknown, name)
		}
	}
	var parts []string
	if len(missing) > 0 {
		parts = append(parts, fmt.Sprintf("missing %d of the %d slots: %s", len(missing), len(slotNames), strings.Join(missing, ", ")))
	}
	if len(unknown) > 0 {
		parts = append(parts, fmt.Sprintf("%d unknown: %s", len(unknown), strings.Join(unknown, ", ")))
	}
	if len(parts) > 0 {
		return fmt.Errorf("a theme publishes every slot the GUI resolves, exactly: %s", strings.Join(parts, "; "))
	}
	return nil
}

// Live is the daemon's last published theme: one per daemon, not per window. With several
// windows the last writer wins, which is right since the theme is one per user. Safe for
// concurrent use.
type Live struct {
	mu  sync.RWMutex
	cur *Frame
}

// NewLive returns a Live with nothing published: it serves the defaults.
func NewLive() *Live { return &Live{} }

// Publish checks f and makes it the current theme. A refused frame changes nothing: the
// last good theme (or the defaults) stays served.
func (l *Live) Publish(f Frame) error {
	if err := f.Check(); err != nil {
		return err
	}
	f = f.clone()
	l.mu.Lock()
	l.cur = &f
	l.mu.Unlock()
	return nil
}

// Current returns the published theme, and false while nothing has been published.
func (l *Live) Current() (Frame, bool) {
	l.mu.RLock()
	defer l.mu.RUnlock()
	if l.cur == nil {
		return Frame{}, false
	}
	return l.cur.clone(), true
}

// CSS is /cf/theme.css: the published theme's slots on :root with its color-scheme, then
// frame.css. Before anything is published, GitHub Dark, and GitHub Light under
// prefers-color-scheme: light, so a page loaded before the GUI connects still follows
// the system.
func (l *Live) CSS() string {
	var b strings.Builder
	if f, ok := l.Current(); ok {
		b.WriteString("/* Code Foundry theme: " + f.ID + " (" + f.Scheme + "), published by the GUI. */\n")
		writeRoot(&b, f, "")
	} else {
		b.WriteString("/* Code Foundry theme: nothing published yet; the defaults follow the system. */\n")
		writeRoot(&b, DefaultFrame(SchemeDark), "")
		b.WriteString("@media (prefers-color-scheme: light) {\n")
		writeRoot(&b, DefaultFrame(SchemeLight), "  ")
		b.WriteString("}\n")
	}
	b.WriteString(frameCSS)
	return b.String()
}

// PinnedCSS is /cf/theme.css?scheme=<scheme>, for a page that is always light or always
// dark (docs/notes/page-library-fixes-a.md): the published theme when it is of that scheme,
// else that scheme's default, then frame.css. The bridge leaves such a page's slots alone
// when the app switches to the other scheme.
func (l *Live) PinnedCSS(scheme string) string {
	var b strings.Builder
	if f, ok := l.Current(); ok && f.Scheme == scheme {
		b.WriteString("/* Code Foundry theme: " + f.ID + " (" + f.Scheme + "), published by the GUI, pinned to " + scheme + ". */\n")
		writeRoot(&b, f, "")
	} else {
		f := DefaultFrame(scheme)
		b.WriteString("/* Code Foundry theme: " + f.ID + ", the " + scheme + " default, pinned. */\n")
		writeRoot(&b, f, "")
	}
	b.WriteString(frameCSS)
	return b.String()
}

func writeRoot(b *strings.Builder, f Frame, indent string) {
	b.WriteString(indent + ":root {\n")
	b.WriteString(indent + "  color-scheme: " + f.Scheme + ";\n")
	for _, name := range slices.Sorted(maps.Keys(f.Vars)) {
		b.WriteString(indent + "  " + name + ": " + f.Vars[name] + ";\n")
	}
	b.WriteString(indent + "}\n")
}

// FrameJSON is /cf/theme.json's body: the theme a script should paint with.
type FrameJSON struct {
	Frame
	// Published is false while the GUI has not published: the frame is GitHub Dark, and
	// Light is the system-light default the stylesheet switches to.
	Published bool `json:"published"`
}

// JSON is /cf/theme.json: the published theme, else GitHub Dark with published false.
func (l *Live) JSON() FrameJSON {
	if f, ok := l.Current(); ok {
		return FrameJSON{Frame: f, Published: true}
	}
	return FrameJSON{Frame: DefaultFrame(SchemeDark)}
}

// FrameHandler serves GET /cf/theme.css (?scheme=dark or light pins it, PinnedCSS) and
// /cf/theme.json from live; any other path under
// /cf/ is 404. It needs no credential (an <iframe>'s stylesheet link sends no header) and
// reveals only colours. Never cached (a theme change must reach the next load), any origin
// (the preview's pages are opaque-origin and may fetch the JSON).
func FrameHandler(live *Live) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Access-Control-Allow-Origin", "*")
		if r.URL.Path != FrameCSSPath && r.URL.Path != FrameJSONPath {
			http.NotFound(w, r)
			return
		}
		if r.Method != http.MethodGet && r.Method != http.MethodHead {
			w.Header().Set("Allow", "GET, HEAD")
			http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
			return
		}
		h := w.Header()
		h.Set("Cache-Control", "no-store")
		h.Set("X-Content-Type-Options", "nosniff")
		if r.URL.Path == FrameCSSPath {
			h.Set("Content-Type", "text/css; charset=utf-8")
			css := live.CSS()
			if s := r.URL.Query().Get("scheme"); s == SchemeDark || s == SchemeLight {
				css = live.PinnedCSS(s)
			}
			_, _ = w.Write([]byte(css))
			return
		}
		body, err := json.Marshal(live.JSON())
		if err != nil {
			http.Error(w, "internal error", http.StatusInternalServerError)
			return
		}
		h.Set("Content-Type", "application/json; charset=utf-8")
		_, _ = w.Write(append(body, '\n'))
	})
}
